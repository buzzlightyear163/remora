// Generates public/images/remora-logo.svg: the hero's particle whale (same seeded geometry,
// same orientation and colors as src/lib/sea.ts), flattened to a crisp SVG for the nav/footer logo.
// Run: npm run logo   (re-run after changing the whale colors in sea.ts)
import { writeFileSync } from 'node:fs';

const OUT = new URL('../public/images/remora-logo.svg', import.meta.url);
const N = +(process.argv[2] || 1500);          // particles in the logo (hero uses 24000)
const COL_A = [0x3d, 0x92, 0xea];               // uA in sea.ts
const COL_B = [0xcf, 0xe8, 0xff];               // uB in sea.ts

const smoothstep = (x, a, b) => { const t = Math.min(1, Math.max(0, (x - a) / (b - a))); return t * t * (3 - 2 * t); };

// --- identical to whalePoints() in src/lib/sea.ts ---
function whalePoints(n) {
  const P = []; let s = 3; const r = () => (s = (s * 16807) % 2147483647) / 2147483647;
  const L = 6.4, X0 = -3.4;
  const rad = u => 0.98 * Math.pow(Math.max(0.02, Math.sin(Math.PI * Math.min(1, u))), 0.62) * (0.18 + 0.82 * smoothstep(u, 0.05, 0.55));
  for (let i = 0; i < n; i++) {
    const kind = r(); let x, y, z, k;
    if (kind < 0.74) {
      const u = Math.min(0.997, Math.pow(r(), 0.85)), a = r() * Math.PI * 2, R = rad(u) * (0.94 + r() * 0.06);
      x = X0 + u * L; y = Math.sin(a) * R * (Math.sin(a) < 0 ? 0.78 : 0.9); z = Math.cos(a) * R;
      const groove = Math.sin(a) < -0.35 && u > 0.55 ? 0.5 + 0.5 * Math.sin(z * 26) : 0;
      k = 0.35 + 0.65 * Math.max(0, Math.sin(a)) * 0.8 + groove * 0.25;
    } else if (kind < 0.88) {
      const side = r() < 0.5 ? -1 : 1, t = r(), w = r();
      x = X0 - 0.15 - t * 0.55 + w * 0.25 * (1 - t); z = side * (0.12 + t * 1.45) * (0.75 + w * 0.25); y = (r() - 0.5) * 0.06 + t * t * 0.18; k = 0.55 + t * 0.4;
    } else {
      const side = r() < 0.5 ? -1 : 1, t = r(), w = (r() - 0.5) * (0.42 - t * 0.3);
      x = 0.9 - t * 1.25 + w * 0.5; z = side * (0.75 + t * 1.55); y = -0.42 - t * 0.38 + (r() - 0.5) * 0.04; k = 0.45 + t * 0.45;
    }
    P.push({ x, y, z, s: 0.55 + r() * 0.9, k: Math.min(1, k) });
  }
  return P;
}

// --- pose: same as the hero (rotation.y ≈ 0.86π, tail wave from the vertex shader) ---
const T = 4.2; // shader time, picked so the tail is lifted mid-stroke
const ry = Math.PI * 0.86, rx = 0.03, rz = -0.02;
const cy = Math.cos(ry), sy = Math.sin(ry), cx = Math.cos(rx), sx = Math.sin(rx), cz = Math.cos(rz), sz = Math.sin(rz);
const CAM = 13;

const pts = whalePoints(N).map(p => {
  const tail = smoothstep(p.x, 1.2, -3.4);
  let { x, y, z } = p;
  y += Math.sin(T * 1.5 - x * 0.9) * 0.2 * tail * tail;
  z += Math.sin(T * 0.7 + x * 0.4) * 0.03;
  // rotate Y, then X, then Z
  let X = x * cy + z * sy, Z = -x * sy + z * cy, Y = y;
  [Y, Z] = [Y * cx - Z * sx, Y * sx + Z * cx];
  [X, Y] = [X * cz - Y * sz, X * sz + Y * cz];
  const persp = CAM / (CAM - Z);
  return { X: X * persp, Y: -Y * persp, d: Z, s: p.s * persp, k: p.k };
});

// fit to a tight viewBox
const pad = 0.12;
const minX = Math.min(...pts.map(p => p.X)) - pad, maxX = Math.max(...pts.map(p => p.X)) + pad;
const minY = Math.min(...pts.map(p => p.Y)) - pad, maxY = Math.max(...pts.map(p => p.Y)) + pad;
const W = 100, H = +(W * (maxY - minY) / (maxX - minX)).toFixed(2);
const sc = W / (maxX - minX);

const hex = c => '#' + c.map(v => Math.round(v).toString(16).padStart(2, '0')).join('');
const mix = k => hex(COL_A.map((a, i) => a + (COL_B[i] - a) * k));

pts.sort((a, b) => a.d - b.d); // back to front
const circles = pts.map(p => {
  const cxp = ((p.X - minX) * sc).toFixed(1), cyp = ((p.Y - minY) * sc).toFixed(1);
  const r = (0.34 * p.s).toFixed(2);
  const o = ((0.55 + 0.45 * p.k) * 0.9).toFixed(2);
  return `<circle cx="${cxp}" cy="${cyp}" r="${r}" fill="${mix(p.k)}" fill-opacity="${o}"/>`;
}).join('');

const svg = `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 ${W} ${H}" width="${W}" height="${H}">
<!-- Remora logo: the hero's particle whale (${N} points). Generated by scripts/gen-whale-logo.mjs -->
<defs><filter id="glow" x="-10%" y="-20%" width="120%" height="140%"><feGaussianBlur stdDeviation="1.1"/></filter></defs>
<defs><g id="w">${circles}</g></defs>
<use href="#w" filter="url(#glow)" opacity=".55"/>
<use href="#w"/>
</svg>
`;
writeFileSync(OUT, svg);
console.log(`wrote ${OUT.pathname}  viewBox 0 0 ${W} ${H}  (${(svg.length / 1024).toFixed(1)} KB)`);
